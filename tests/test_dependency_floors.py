"""The dependency versions that closed a Dependabot finding stay closed.

WHY THIS FILE EXISTS

A lockfile can be regenerated by someone who does not know why a version was pinned, and nothing
in the normal test run would notice: the suite does not exercise a lock file. Dependabot alerts
the repository, but only once the advisory is public and only on the default branch. This file
turns each fixed floor into a check that runs with the rest of the suite, so a regeneration that
drops a fixed version fails here before it reaches a release.

Each floor is the first patched version Dependabot named for the advisories that were closed. A
floor is raised only when a finding is closed, never lowered.
"""
import json
import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent

#: (lock file, package name, minimum version) for every finding closed by the triage.
#: Cargo.lock names the package in TOML, the npm lock files name it under node_modules/.
FLOORS = (
    ("rust/Cargo.lock", "pyo3", "0.29.0"),
    ("web/package-lock.json", "next", "16.3.6"),
    ("web/package-lock.json", "undici", "7.29.1"),
    ("docs/package-lock.json", "@vue/server-renderer", "3.5.42"),
    ("docs/package-lock.json", "vue", "3.5.42"),
    ("docs/package-lock.json", "esbuild", "0.25.0"),
)


def _version_tuple(text):
    return tuple(int(part) for part in text.split("."))


def _versions_in_cargo_lock(text):
    found = {}
    for name, version in re.findall(r'name = "([^"]+)"\nversion = "([^"]+)"', text):
        found.setdefault(name, []).append(version)
    return found


def _versions_in_npm_lock(text):
    packages = json.loads(text).get("packages", {})
    found = {}
    for key, meta in packages.items():
        if not key.startswith("node_modules/"):
            continue
        name = key.rsplit("node_modules/", 1)[1]
        found.setdefault(name, []).append(meta.get("version", ""))
    return found


def violations(lock_name, text, package, floor):
    """Every installed copy of `package` below `floor`, and an empty list when all are at or above.

    An absent package is a violation too: a floor that stops matching anything is a floor nobody
    is checking any more, which is the failure this file exists to catch.
    """
    reader = _versions_in_cargo_lock if lock_name.endswith(".lock") else _versions_in_npm_lock
    versions = reader(text).get(package)
    if not versions:
        return [f"{package} is not in {lock_name} at all"]
    return [f"{package} {v} in {lock_name}, below the floor {floor}"
            for v in versions if _version_tuple(v) < _version_tuple(floor)]


@pytest.mark.parametrize(("lock_name", "package", "floor"), FLOORS)
def test_the_closed_finding_is_still_closed(lock_name, package, floor):
    text = (REPO / lock_name).read_text(encoding="utf-8")
    assert violations(lock_name, text, package, floor) == []


def test_a_cargo_lock_at_the_vulnerable_version_is_a_violation():
    old = 'name = "pyo3"\nversion = "0.27.2"\nsource = "registry+x"\n'
    assert violations("rust/Cargo.lock", old, "pyo3", "0.29.0") == [
        "pyo3 0.27.2 in rust/Cargo.lock, below the floor 0.29.0"]


def test_an_npm_lock_with_the_vulnerable_nested_copy_is_a_violation():
    lock = json.dumps({"packages": {
        "node_modules/undici": {"version": "7.29.0"},
        "node_modules/wrangler/node_modules/undici": {"version": "7.29.1"},
    }})
    assert violations("web/package-lock.json", lock, "undici", "7.29.1") == [
        "undici 7.29.0 in web/package-lock.json, below the floor 7.29.1"]


def test_an_npm_package_that_vanished_from_the_lock_is_a_violation():
    lock = json.dumps({"packages": {"node_modules/other": {"version": "1.0.0"}}})
    assert violations("docs/package-lock.json", lock, "esbuild", "0.25.0") == [
        "esbuild is not in docs/package-lock.json at all"]


def test_a_version_at_the_floor_is_not_a_violation():
    lock = json.dumps({"packages": {"node_modules/esbuild": {"version": "0.25.0"}}})
    assert violations("docs/package-lock.json", lock, "esbuild", "0.25.0") == []


def test_versions_compare_numerically_not_as_text():
    lock = json.dumps({"packages": {"node_modules/next": {"version": "16.3.10"}}})
    assert violations("web/package-lock.json", lock, "next", "16.3.6") == []
